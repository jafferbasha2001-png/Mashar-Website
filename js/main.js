/* =====================================================
   NUMBER COUNTERS
===================================================== */

const counters =
    document.querySelectorAll(
        "[data-count]"
    );


const counterObserver =
    new IntersectionObserver(

        entries => {

            entries.forEach(
                entry => {

                    if (
                        !entry.isIntersecting
                    ) {

                        return;

                    }


                    const element =
                        entry.target;


                    const target =
                        Number(
                            element.dataset.count
                        );


                    const duration =
                        900;


                    const start =
                        performance.now();


                    function animate(
                        currentTime
                    ) {

                        const progress =
                            Math.min(
                                (
                                    currentTime -
                                    start
                                ) / duration,
                                1
                            );


                        const eased =
                            1 -
                            Math.pow(
                                1 - progress,
                                3
                            );


                        element.textContent =
                            Math.floor(
                                target * eased
                            );


                        if (
                            progress < 1
                        ) {

                            requestAnimationFrame(
                                animate
                            );

                        }

                    }


                    requestAnimationFrame(
                        animate
                    );


                    counterObserver.unobserve(
                        element
                    );

                }
            );

        },

        {
            threshold: 0.5
        }

    );


counters.forEach(
    counter => {

        counterObserver.observe(
            counter
        );

    }
);

