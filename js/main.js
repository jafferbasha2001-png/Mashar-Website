document.addEventListener("DOMContentLoaded", function () {

    const carousel =
        document.getElementById("testimonialCarousel");

    const track =
        document.getElementById("testimonialTrack");

    const prevButton =
        document.getElementById("testimonialPrev");

    const nextButton =
        document.getElementById("testimonialNext");

    const dotsContainer =
        document.getElementById("testimonialDots");

    if (!carousel || !track || !prevButton || !nextButton || !dotsContainer) {
        return;
    }

    const cards =
        Array.from(track.querySelectorAll(".testimonial-card"));

    let currentIndex = 0;
    let autoSlideTimer = null;


    function cardsVisible() {

        if (window.innerWidth <= 620) {
            return 1;
        }

        if (window.innerWidth <= 900) {
            return 2;
        }

        return 3;
    }


    function maxIndex() {

        return Math.max(
            0,
            cards.length - cardsVisible()
        );
    }


    function createDots() {

        dotsContainer.innerHTML = "";

        for (let index = 0; index <= maxIndex(); index++) {

            const dot =
                document.createElement("button");

            dot.type = "button";

            dot.className =
                "testimonial-dot";

            dot.setAttribute(
                "aria-label",
                "Show testimonial group " + (index + 1)
            );

            dot.addEventListener(
                "click",
                function () {

                    currentIndex = index;

                    updateCarousel();

                    restartAutoSlide();

                }
            );

            dotsContainer.appendChild(dot);

        }

    }


    function updateCarousel() {

        const maximum =
            maxIndex();

        if (currentIndex > maximum) {
            currentIndex = maximum;
        }

        const firstCard =
            cards[0];

        if (!firstCard) {
            return;
        }

        const cardWidth =
            firstCard.getBoundingClientRect().width;

        const trackStyle =
            window.getComputedStyle(track);

        const gap =
            parseFloat(trackStyle.columnGap || trackStyle.gap) || 0;

        const offset =
            currentIndex * (cardWidth + gap);

        const rtl =
            document.documentElement.dir === "rtl";

        track.style.transform =
            "translateX(" +
            (rtl ? offset : -offset) +
            "px)";

        const dots =
            dotsContainer.querySelectorAll(".testimonial-dot");

        dots.forEach(
            function (dot, index) {

                dot.classList.toggle(
                    "active",
                    index === currentIndex
                );

            }
        );

    }


    function showNext() {

        currentIndex =
            currentIndex >= maxIndex()
                ? 0
                : currentIndex + 1;

        updateCarousel();

    }


    function showPrevious() {

        currentIndex =
            currentIndex <= 0
                ? maxIndex()
                : currentIndex - 1;

        updateCarousel();

    }


    function stopAutoSlide() {

        if (autoSlideTimer) {

            clearInterval(
                autoSlideTimer
            );

            autoSlideTimer = null;

        }

    }


    function startAutoSlide() {

        stopAutoSlide();

        autoSlideTimer =
            setInterval(
                showNext,
                6000
            );

    }


    function restartAutoSlide() {

        startAutoSlide();

    }


    prevButton.addEventListener(
        "click",
        function () {

            showPrevious();

            restartAutoSlide();

        }
    );


    nextButton.addEventListener(
        "click",
        function () {

            showNext();

            restartAutoSlide();

        }
    );


    carousel.addEventListener(
        "mouseenter",
        stopAutoSlide
    );


    carousel.addEventListener(
        "mouseleave",
        startAutoSlide
    );


    carousel.addEventListener(
        "focusin",
        stopAutoSlide
    );


    carousel.addEventListener(
        "focusout",
        startAutoSlide
    );


    let resizeTimer;

    window.addEventListener(
        "resize",
        function () {

            clearTimeout(
                resizeTimer
            );

            resizeTimer =
                setTimeout(
                    function () {

                        createDots();

                        updateCarousel();

                    },
                    150
                );

        }
    );


    /* Reposition correctly after English / Arabic direction changes. */
    const directionObserver =
        new MutationObserver(
            function () {

                setTimeout(
                    updateCarousel,
                    50
                );

            }
        );

    directionObserver.observe(
        document.documentElement,
        {
            attributes: true,
            attributeFilter: ["dir"]
        }
    );


    createDots();

    updateCarousel();

    startAutoSlide();

});


