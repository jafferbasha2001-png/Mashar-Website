/* =====================================================
   GET NESTED TRANSLATION
===================================================== */

function getTranslation(dictionary, key) {

    return key
        .split(".")
        .reduce(
            (object, property) =>
                object?.[property],
            dictionary
        );

}



/* =====================================================
   SET LANGUAGE
===================================================== */

function setLanguage(language) {

    const dictionary =
        translations[language];


    if (!dictionary) {
        return;
    }


    /* Change HTML language */

    document.documentElement.lang =
        language;


    /* Change direction */

    document.documentElement.dir =
        language === "ar"
            ? "rtl"
            : "ltr";


    /* Update normal text */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.dataset.i18n;

            const value =
                getTranslation(
                    dictionary,
                    key
                );

            if (value !== undefined) {

                element.textContent =
                    value;

            }

        });


    /* Update placeholders */

    document
        .querySelectorAll(
            "[data-i18n-placeholder]"
        )
        .forEach(element => {

            const key =
                element.dataset.i18nPlaceholder;

            const value =
                getTranslation(
                    dictionary,
                    key
                );

            if (value !== undefined) {

                element.placeholder =
                    value;

            }

        });


    /* Update language button */

    const languageBtn =
        document.getElementById(
            "languageBtn"
        );


    languageBtn.textContent =
        language === "ar"
            ? "English"
            : "العربية";


    /* Save preference */

    localStorage.setItem(
        "masharLanguage",
        language
    );

}



